// Each run starts in a fresh process: require() must not retain old layouts.
const { resolve } = require('node:path');
(async () => {
  const { root, output, hash, fingerprint, atomicWrite } = await import('./td4-details.mjs');
  const before = await fingerprint();
  const { specs, definition } = require('../workbench/td4_v2/details.js');
  const files = {}, metadata = {}, artifacts = {}, contents = {};
  for (const [id, spec] of Object.entries(specs)) for (const edition of ['classic', 'wide']) {
    const prefix = edition === 'wide' ? 'wide:' : '';
    const definitions = Object.fromEntries(['module', 'nand', 'mos'].map(view => [prefix + id + view, definition(id, view, edition)]));
    const content = '// Generated by npm run generate:td4-details. Do not edit.\nObject.assign(globalThis.FlowV2Precomputed.definitions,' + JSON.stringify(definitions) + ');\n';
    const filename = `${edition === 'wide' ? 'wide-' : ''}${id}.${hash(content).slice(0, 16)}.js`;
    files[prefix + id] = filename; metadata[id] = { title: spec.title, ports: spec.ports };
    contents[filename] = content; artifacts[filename] = hash(content);
  }
  if ((await fingerprint()).hash !== before.hash) {
    console.log('[td4-details] Sources changed during calculation; retrying without publishing.');
    return;
  }
  // Immutable, content-addressed files keep already-open pages usable after a
  // rebuild. Publish the index only after every referenced file is complete.
  for (const [file, content] of Object.entries(contents)) await atomicWrite(resolve(output, file), content);
  const index = '// Generated by npm run generate:td4-details. Do not edit.\nglobalThis.FlowV2Precomputed=' + JSON.stringify({ specs: metadata, files, definitions: {} }) + ';\n';
  await atomicWrite(resolve(output, 'index.js'), index);
  artifacts['index.js'] = hash(index);
  await atomicWrite(resolve(output, 'manifest.json'), JSON.stringify({ sourceHash: before.hash, inputs: before.inputs, artifacts, files }, null, 2) + '\n');
  console.log(`[td4-details] Saved ${Object.keys(files).length} module editions × 3 circuits (4 display modes).`);
})().catch(error => { console.error(error); process.exitCode = 1; });
